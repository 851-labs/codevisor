/// Keyboard keys as the simulator's HID keyboard (usage page 7) knows them. iOS reports HID
/// usages directly (`UIKeyboardHIDUsage`); a Mac reports virtual key codes, mapped here.
enum SimulatorKeyboard {
  static let leftControl = 0xE0
  static let leftShift = 0xE1
  static let leftOption = 0xE2
  static let leftCommand = 0xE3
  static let rightControl = 0xE4
  static let rightShift = 0xE5
  static let rightOption = 0xE6
  static let rightCommand = 0xE7
  static let capsLock = 0x39

  static let modifierUsages: Set<Int> = [
    leftControl, leftShift, leftOption, leftCommand, rightControl, rightShift, rightOption, rightCommand, capsLock,
  ]

  /// macOS virtual key code (Carbon `kVK_*`) → HID keyboard usage.
  static func usage(macKeyCode code: UInt16) -> Int? { macToHID[code] }

  /// A typed character on the simulator's US keyboard: its key and whether Shift makes it.
  /// Mapping the character rather than the Mac's key keeps other Mac layouts (and text sent
  /// without real key codes) typing what was meant.
  static func key(for character: Character) -> (usage: Int, shift: Bool)? {
    if let usage = unshifted[character] { return (usage, false) }
    if let usage = shifted[character] { return (usage, true) }
    if character.isUppercase, let lower = character.lowercased().first, let usage = unshifted[lower] {
      return (usage, true)
    }
    return nil
  }

  private static let unshifted: [Character: Int] = {
    var map: [Character: Int] = [
      " ": 0x2C, "-": 0x2D, "=": 0x2E, "[": 0x2F, "]": 0x30, "\\": 0x31, ";": 0x33,
      "'": 0x34, "`": 0x35, ",": 0x36, ".": 0x37, "/": 0x38,
    ]
    for (offset, letter) in "abcdefghijklmnopqrstuvwxyz".enumerated() { map[letter] = 0x04 + offset }
    for (offset, digit) in "1234567890".enumerated() { map[digit] = 0x1E + offset }
    return map
  }()

  private static let shifted: [Character: Int] = {
    var map: [Character: Int] = [
      "_": 0x2D, "+": 0x2E, "{": 0x2F, "}": 0x30, "|": 0x31, ":": 0x33, "\"": 0x34,
      "~": 0x35, "<": 0x36, ">": 0x37, "?": 0x38,
    ]
    for (offset, symbol) in "!@#$%^&*()".enumerated() { map[symbol] = 0x1E + offset }
    return map
  }()

  private static let macToHID: [UInt16: Int] = [
    // Letters (ANSI positions).
    0x00: 0x04, 0x0B: 0x05, 0x08: 0x06, 0x02: 0x07, 0x0E: 0x08, 0x03: 0x09, 0x05: 0x0A, 0x04: 0x0B,
    0x22: 0x0C, 0x26: 0x0D, 0x28: 0x0E, 0x25: 0x0F, 0x2E: 0x10, 0x2D: 0x11, 0x1F: 0x12, 0x23: 0x13,
    0x0C: 0x14, 0x0F: 0x15, 0x01: 0x16, 0x11: 0x17, 0x20: 0x18, 0x09: 0x19, 0x0D: 0x1A, 0x07: 0x1B,
    0x10: 0x1C, 0x06: 0x1D,
    // Digits.
    0x12: 0x1E, 0x13: 0x1F, 0x14: 0x20, 0x15: 0x21, 0x17: 0x22, 0x16: 0x23, 0x1A: 0x24, 0x1C: 0x25,
    0x19: 0x26, 0x1D: 0x27,
    // Return, Escape, Delete, Tab, Space.
    0x24: 0x28, 0x35: 0x29, 0x33: 0x2A, 0x30: 0x2B, 0x31: 0x2C,
    // Punctuation: - = [ ] \ ; ' ` , . /
    0x1B: 0x2D, 0x18: 0x2E, 0x21: 0x2F, 0x1E: 0x30, 0x2A: 0x31, 0x29: 0x33, 0x27: 0x34, 0x32: 0x35,
    0x2B: 0x36, 0x2F: 0x37, 0x2C: 0x38,
    // Caps Lock, F1–F12.
    0x39: 0x39, 0x7A: 0x3A, 0x78: 0x3B, 0x63: 0x3C, 0x76: 0x3D, 0x60: 0x3E, 0x61: 0x3F, 0x62: 0x40,
    0x64: 0x41, 0x65: 0x42, 0x6D: 0x43, 0x67: 0x44, 0x6F: 0x45,
    // Home, Page Up, Forward Delete, End, Page Down, arrows.
    0x73: 0x4A, 0x74: 0x4B, 0x75: 0x4C, 0x77: 0x4D, 0x79: 0x4E, 0x7C: 0x4F, 0x7B: 0x50, 0x7D: 0x51,
    0x7E: 0x52,
    // Keypad.
    0x4B: 0x54, 0x43: 0x55, 0x4E: 0x56, 0x45: 0x57, 0x4C: 0x58, 0x53: 0x59, 0x54: 0x5A, 0x55: 0x5B,
    0x56: 0x5C, 0x57: 0x5D, 0x58: 0x5E, 0x59: 0x5F, 0x5B: 0x60, 0x5C: 0x61, 0x52: 0x62, 0x41: 0x63,
    0x51: 0x67,
    // Modifiers.
    0x3B: leftControl, 0x38: leftShift, 0x3A: leftOption, 0x37: leftCommand, 0x3E: rightControl,
    0x3C: rightShift, 0x3D: rightOption, 0x36: rightCommand,
  ]
}
