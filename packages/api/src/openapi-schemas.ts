export type JsonObject = Record<string, unknown>

export const jsonSchema = (schema: Schema.Constraint): JsonObject => {
  const document = Schema.toJsonSchemaDocument(schema, {
    additionalProperties: false,
    generateDescriptions: true
  })
  return { ...document.schema, $defs: document.definitions }
}

export const arrayOf = (schema: Schema.Constraint): Schema.Constraint => Schema.Array(schema)
export const nullable = (schema: Schema.Constraint): Schema.Constraint => Schema.NullOr(schema)

